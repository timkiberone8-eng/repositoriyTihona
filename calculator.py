# Разбор занятия 13.09. Код твой, правки помечены комментариями.
#
# ГЛАВНАЯ ОШИБКА БЫЛА ЗДЕСЬ, в строке с вводом операции:
#
#     x = input("...").upper().strip()
#     if x == "сложение":
#
# .upper() делает из введённого "СЛОЖЕНИЕ" — все буквы заглавные.
# А сравниваем мы с "сложение" — все буквы маленькие.
# "СЛОЖЕНИЕ" == "сложение" это False. Всегда. При любом вводе.
#
# Поэтому программа не падала и не ругалась: она честно проверяла
# все четыре if, ни один не совпадал, и она доходила до конца и выходила.
# Ничего не напечатав. Код завершения 0, то есть "всё прошло успешно".
#
# Это важный тип ошибки: программа НЕ сломалась, она сделала не то.
# try/except такое не ловит, потому что ловить нечего.
# Ищется только чтением кода и проверкой на живых данных.

# Правка 1: добавлены подсказки в input().
# Было a=int(input()) — пустой чёрный экран, человек не знает, чего от него хотят.
a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))

result = 0

# Правка 2: .upper() заменён на .lower().
# Теперь "Сложение", "СЛОЖЕНИЕ" и "сложение" превращаются в "сложение"
# и совпадают с тем, что написано в if.
#
# Правка 3: порядок .lower().strip() оставлен как у тебя — он рабочий.
# .strip() убирает пробелы по краям, .lower() опускает регистр,
# и в каком порядке их вызывать, роли не играет.
x = input("Введите операцию (сложение, вычитание, умножение, деление): ").lower().strip()

# Правка 4: цепочка отдельных if заменена на if/elif/else.
# Было четыре независимых if: Python проверял все четыре, даже когда
# первый уже совпал. С elif он останавливается на первом подошедшем.
# А else ловит всё остальное — без него опечатка снова давала бы тишину.
if x == "сложение":
    result = a + b
elif x == "вычитание":
    result = a - b
elif x == "умножение":
    result = a * b
elif x == "деление":
    # Осторожно: если b == 0, здесь программа упадёт с ZeroDivisionError.
    # Это как раз тема урока 3, чиним через try/except.
    result = a / b
else:
    result = "Неизвестная операция"

# Правка 5: один print в конце вместо четырёх внутри веток.
# Так печать не забудется ни в одной ветке, и её легко поменять в одном месте.
print(f"Результат: {result}")
