from calculator_modules.arithmetic import add, subtract, multiply, divide;
from advanced import power, square_root;

class NegativeNumberError(Exception):
            """исключение если отрицательное число"""
            pass

def main():
    try:
        x=int(input())
        y=int(input())

        result=0
        a = input("введите операцию (сложение,вычитание,умножение,деление,стпень,корень-только первое число,второе-любое)").lower().strip()
        if a=="сложение":
            result=add(x,y)
            print(result)

        if a=="вычитание":
            result=subtract(x,y)
            print(result)

        if a=="умножение":
            result=multiply(x,y)
            print(result)


        if a=="деление":
            result=divide(x,y)
            print(result)

        if a=="степень":
            result=power(x,y)
            print(result)


        def sqrt_with_check(x):
            """корень с проверкой.Для отрицательного числа выбрасывает свое исключение"""
            if x<0:
                raise NegativeNumberError("ошибка:корень из отрицательного числа не определен")
            return x**0.5

        if a=="корень":
            result=sqrt_with_check(x)
            print(result)


    # Эта ветка была закомментирована. Вместе с ошибкой в divide()
    # получалось два замка на одной двери: исключение не возникало,
    # а если бы возникло, ловить его было некому.
    except ZeroDivisionError:
        print("нельзя делить на ноль")


    except ValueError:
        print("введите правильный тип данных")


    except NegativeNumberError as e:
        print(e)

    finally:
        print("завершено")


# БЫЛО: этот блок лежал ВНУТРИ функции main(), закомментированный,
# с отступом в восемь пробелов:
#
#         # if __name__ == "__main__":
#         #     main()
#
# Из-за этого main() не вызывалась вообще, и программа запускалась,
# молча доходила до конца файла и завершалась с кодом 0. Ни ошибки,
# ни вывода: самый неприятный вид поломки, потому что он выглядит
# как "всё нормально".
#
# А если бы блок просто раскомментировали на том же месте, стало бы
# хуже: main() вызывала бы саму себя изнутри самой себя, и получилась
# бы бесконечная рекурсия.
#
# СТАЛО: блок стоит в самом низу файла, от нулевой колонки, после всех
# объявлений. Это его единственное правильное место.
#
# Что значит сама строка: __name__ это переменная, которую Python
# заводит в каждом файле сам. Если файл ЗАПУСТИЛИ (python main.py),
# в неё попадает "__main__". Если файл ПОДКЛЮЧИЛИ из другого файла
# (import main), туда попадает имя модуля, то есть "main".
# Читается строка так: "вызывай main() только когда меня запустили,
# а не когда меня подключили".
if __name__ == "__main__":
    main()